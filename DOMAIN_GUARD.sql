-- Одне поле, і саме його бракувало, щоб відповісти на питання «домен
-- зламався — що на ньому зараз крутиться». До цього база знала про
-- оголошення все, крім того, куди воно веде: fb-sync брав із креативу
-- лише effective_object_story_id, і то заради Сторінок.
--
-- Тримаємо ХОСТ, а не посилання цілком. Посилання в оголошенні несе
-- мітки, sub-id і часом дані людини; складати це в таблицю, яку читає
-- вся команда, не варто, а для стикування зі списком доменів потрібен
-- усе одно тільки хост.
--
-- www. знімаємо ще в функції: у списку доменів його не пишуть, і
-- стикування за точною рівністю на ньому б мовчки провалювалось.
--
-- Виконати: Supabase → SQL Editor → Run.

alter table public.fb_ad_today
  add column if not exists link_domain text;

-- Індекс саме під зворотне питання: не «куди веде це оголошення», а
-- «що живе на цьому домені». Перше й так швидке за первинним ключем,
-- друге без індексу означало б перебір усього знімка.
create index if not exists fb_ad_today_link_domain_idx
  on public.fb_ad_today (link_domain)
  where link_domain is not null;
