--
--  СИМПТОМ. Змінюєш шаблон розбору APP (чи мапу Keitaro, чи щось інше
--  в налаштуваннях), тиснеш Save — і нічого не зберігається. До цієї
--  правки сторінка ще й писала «saved», бо не дивилась на відповідь
--  бази взагалі (PostgREST відмову не кидає винятком, він повертає її
--  в полі error). Тепер вона скаже, що не збереглось, і покаже цей
--  файл. Але полагодити це в коді не можна — причина в даних.
--
--  ПРИЧИНА. У team_settings один рядок на (team_name, key) — так
--  зроблено унікальним індексом. А політики зі SECURITY_BUYERS.sql
--  пускають до рядка лише його автора: created_by = auth.uid().
--
--  Поки команда одна й людина одна, ці два правила не сваряться.
--  Сваряться вони після ЗЛИТТЯ двох назв команди в одну
--  (TEAM_RENAME.sql, блоки ЗЛИТТЯ): під новою назвою лишились рядки,
--  заведені іншою людиною — наприклад асистентом. І тоді:
--
--    читання   — RLS їх не віддає, тож у полях на сторінці стоять
--                ТИПОВІ значення, а не те, що лежить у базі;
--    запис     — upsert натикається на їхній унікальний ключ і не
--                проходить (23505 або 42501).
--
--  Тобто налаштування є, вони не твої, і обидві половинки проблеми
--  ззовні виглядають як «нічого не зберігається».
--
--  ЩО РОБИТЬ ЦЕЙ ФАЙЛ. Передає такі рядки тобі. Значення при цьому
--  НЕ змінюються: міняється лише підпис created_by. Після цього
--  сторінка покаже, що насправді лежить у базі, і збереження почне
--  проходити.
--
--  Це налаштування робочого місця (шаблони розбору, мапа колонок,
--  приховані агенти), а не чиїсь особисті дані: жодного рядка
--  daily_stats чи creatives_stats файл не чіпає.
--
--  ⚠️ СПОЧАТКУ ПОДИВИСЬ НА OWN_UNIQUE.sql. Цей файл прибирає НАСЛІДОК:
--  передає тобі рядки, які опинились чужими. Причина ж у тому, що
--  унікальність у team_settings рахувалась по команді, а видимість — по
--  автору; OWN_UNIQUE.sql переводить ключ на власника, і тоді чужий
--  рядок перестає блокувати твій узагалі. Після нього цей файл потрібен
--  лише тоді, коли хочеш ЗАБРАТИ СОБІ саме ті значення, які завів хтось
--  інший, а не завести свої.
--
--  Де запускати: Supabase Dashboard → SQL Editor → New query → Run.
--  Блоки виконувати по одному, згори вниз.
-- ============================================================


-- ════════════════════════════════════════════════════════════
--  ▶ БЛОК 1 — подивитись, що там лежить і чиє воно
--
--  Нічого не міняє. Колонка «чиє» — з team_members, тому імена
--  зʼявляться лише в тих, кого заведено на Admin.html; решта піде
--  початком uuid.
-- ════════════════════════════════════════════════════════════

-- ⬇ ⬇ ⬇  ПОСТАВ СВОЇ ДВА ЗНАЧЕННЯ  ⬇ ⬇ ⬇
--   TEAM    — назва команди, під якою ти сидиш у дашборді
--             (ліва панель, перемикач команди)
--   MY_UUID — твій user id: Supabase → Authentication → Users
select
  s.key                                            as "налаштування",
  case when s.created_by = '00000000-0000-0000-0000-000000000000'::uuid
       then 'ТВОЄ' else 'ЧУЖЕ' end                 as "чиє",
  coalesce(m.name, left(s.created_by::text, 8), '— без автора —') as "автор",
  left(s.value, 60)                                as "значення (початок)"
from public.team_settings s
left join public.team_members m on m.user_id = s.created_by
where s.team_name = 'IMPROVE'                      -- ⬅ TEAM
order by "чиє" desc, s.key;


-- ════════════════════════════════════════════════════════════
--  ▶ БЛОК 2 — передати чужі рядки тобі
--
--  Рядок без автора (created_by is null) теж забираємо: це запис із
--  часів до SECURITY_BUYERS.sql крок 3, коли колонку ще не підписували.
--  Він і зараз нічий, а нічий рядок у team_settings — це той самий
--  блокувальник, тільки без імені.
--
--  Запускати можна скільком завгодно разів: другий запуск не знайде
--  що робити.
-- ════════════════════════════════════════════════════════════

drop table if exists public._ts_log;
create table public._ts_log ("налаштування" text, "було чиє" text, "значення (початок)" text);

do $$
declare
  TEAM    constant text := 'IMPROVE';                                   -- ⬅ та сама команда
  MY_UUID constant uuid := '00000000-0000-0000-0000-000000000000';      -- ⬅ той самий uuid
begin
  insert into public._ts_log
  select s.key,
         coalesce(m.name, left(s.created_by::text, 8), '— без автора —'),
         left(s.value, 60)
    from public.team_settings s
    left join public.team_members m on m.user_id = s.created_by
   where s.team_name = TEAM
     and s.created_by is distinct from MY_UUID;

  update public.team_settings
     set created_by = MY_UUID
   where team_name = TEAM
     and created_by is distinct from MY_UUID;

  if not exists (select 1 from public._ts_log) then
    insert into public._ts_log values
      ('—', '—', 'чужих рядків немає: усі налаштування цієї команди вже твої');
  end if;
end $$;

--  ⬇ ОСЬ ЦЕ Й Є ЗВІТ. Якщо тут порожньо — блок не виконався.
--  (DO-блок рядків не повертає ніколи, а raise notice в SQL Editor
--   не видно — через це перша редакція сусіднього файлу виглядала як
--   «Success. No rows returned», тобто ніяк.)
select * from public._ts_log order by "налаштування";


-- ════════════════════════════════════════════════════════════
--  ▶ БЛОК 3 — перевірка
--
--  Після цього перезавантаж Form.html (Ctrl+Shift+R) і збережи
--  налаштування ще раз: тепер у полях буде те, що справді в базі, а
--  Save пройде.
-- ════════════════════════════════════════════════════════════

select team_name as "команда",
       count(*) as "налаштувань",
       count(*) filter (where created_by is null) as "без автора",
       count(distinct created_by) as "різних авторів"
from public.team_settings
group by 1
order by 2 desc;
