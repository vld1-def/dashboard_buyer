-- ════════════════════════════════════════════════════════════
--  ▶ ДОМЕНИ В СТАТИСТИЦІ (Site)
--
--  ЗАЧИМ. Домен досі жив у двох місцях окремо: у списку доменів
--  (таблиця domains — хто живий, хто в бані) і в оголошеннях Facebook
--  на сьогодні (fb_ad_today.link_domain). Обидва відповідають на
--  питання «що там зараз». А питання «скільки ми на цей домен залили
--  за весь час» не мало де взятись: у daily_stats домену не було.
--
--  Тепер у вигрузці Keitaro є стовпець Site — і домен приїжджає разом
--  зі статистикою, тим самим рядком, що й спенд.
--
--  ЩО ЛЕЖИТЬ У КОЛОНЦІ. Чистий хост у нижньому регістрі:
--  «mplay-kg.website». Без схеми, без www, без шляху — рівно те, за
--  що можна зіставити рядок статистики з рядком у списку доменів.
--  Порожньо, якщо в тому рядку вигрузки домену не було: порожній
--  рядок читався б як «домен без назви».
--
--  ЧОМУ ЦЕ НЕ ЛАМАЄ СУМИ. Імпорт розносить спенд FB по парах
--  (лендінг, домен) пропорційно унікальним клікам — так само, як до
--  цього розносив по лендінгах. Рядків стає більше, а суми по оферах
--  і по лендінгах лишаються ті самі: ділиться те, що й так належало
--  цій групі.
--
--  Виконати: Supabase → SQL Editor → Run. Один раз.
-- ════════════════════════════════════════════════════════════

alter table public.daily_stats
  add column if not exists site text;

-- Питання до цієї колонки одне: «що в нас по цьому домену» (і далі
-- розріз по доменах у Report Builder). Без індексу це перебір усієї
-- таблиці; з ним — читання рівно потрібних рядків. Частковий, бо
-- старі рядки домену не мають і ніколи не матимуть.
create index if not exists daily_stats_site_idx
  on public.daily_stats (team_name, site)
  where site is not null;


-- ════════════════════════════════════════════════════════════
--  ▶ ЗВІТ — що вийшло
-- ════════════════════════════════════════════════════════════
select count(*) as rows_total,
       count(site) as rows_with_site,
       count(distinct site) as domains
from public.daily_stats;
