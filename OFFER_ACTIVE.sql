-- ══════════════════════════════════════════════════════════════════
--  Вимикач оффера: payouts.active
-- ══════════════════════════════════════════════════════════════════
--  Потрібен, щоб оффер можна було вимкнути в Settings і він перестав
--  підтягуватись при імпорті. Актуально, коли два рядки мають однакову
--  назву і відрізняються лише ставкою — інакше в розрахунок виручки
--  потрапляє випадковий з них.
--
--  До виконання цього запиту все працює як раніше: код вважає активним
--  усе, де active не дорівнює false.
--  Запускати в Supabase → SQL Editor.
-- ══════════════════════════════════════════════════════════════════

ALTER TABLE public.payouts
  ADD COLUMN IF NOT EXISTS active boolean NOT NULL DEFAULT true;

-- Перевірка: подивитись, де є дублі за назвою оффера в межах гео —
-- саме їх і має сенс розводити вимикачем.
SELECT team_name, geo, offer,
       count(*)                       AS рядків,
       string_agg(value::text, ' | ') AS ставки
FROM public.payouts
GROUP BY 1, 2, 3
HAVING count(*) > 1
ORDER BY 1, 2, 3;
