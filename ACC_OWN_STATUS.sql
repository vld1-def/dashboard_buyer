-- ═══════════ ВІКНО ACCOUNTS ОТРИМУЄ ВЛАСНИЙ СТАТУС ═══════════
--
-- Досі сторінка Cabinets і модальне вікно Accounts писали статус в
-- ОДНУ колонку — accounts_mapping.status. Той самий рядок, те саме
-- поле. Тому масовий архів у Cabinets приходив у вікно, а вікно про
-- слово "archive" не знало й показувало його як "Активний".
--
-- Після цієї міграції:
--   status      — сторінка Cabinets (active | problem | ban | archive)
--   acc_status  — вікно Accounts, тільки руками (active | problem | ban)
--
-- Виконати в Supabase → SQL Editor. Безпечно запускати повторно.

-- ── 1. Сама колонка ──────────────────────────────────────────────
-- Без DEFAULT навмисно: NULL означає "тут ще нічого не ставили
-- руками", і вікно читає такий рядок як активний. DEFAULT 'active'
-- зробив би "не чіпали" й "подивились і визнали активним" одним і
-- тим самим, а це різні речі.
ALTER TABLE public.accounts_mapping
  ADD COLUMN IF NOT EXISTS acc_status text;

-- ── 2. Переносимо те, що ставили руками ──────────────────────────
-- Статуси, які люди виставляли у вікні, лежать у спільній колонці —
-- загубити їх було б платою за розділення, якої ніхто не просив.
--
-- АРХІВ НЕ ПЕРЕНОСИМО. Він з'явився в цій колонці з Cabinets, і
-- копіювати його у власну колонку вікна означало б зробити третій
-- архів, про який не знає ніхто. Саме по ньому ми й розділяємось.
UPDATE public.accounts_mapping
   SET acc_status = status
 WHERE acc_status IS NULL
   AND status IS NOT NULL
   AND btrim(status) <> ''
   AND lower(btrim(status)) <> 'archive';

-- ── 3. Що вийшло ─────────────────────────────────────────────────
-- Перший рядок — скільки статусів перенесено, другий — скільки
-- рядків лишилось без власного статусу (їх вікно покаже активними).
SELECT coalesce(acc_status, '— не ставили —') AS acc_status,
       count(*) AS rows
  FROM public.accounts_mapping
 GROUP BY 1
 ORDER BY 2 DESC;
