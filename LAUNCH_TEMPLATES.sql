-- ═══════════ ШАБЛОНИ ЗАПУСКІВ ═══════════
--
-- «Зберігаєш набір (гео, бюджет, креативи, апка, домен) під назвою і
-- запускаєш його в новий кабінет одним кліком».
--
-- Шаблон — ЗНІМОК кампанії, а не посилання на неї. Копія з живої
-- кампанії (як було в Copy campaign) вмирає разом із кабінетом-зразком:
-- забанили — копіювати нема з чого. Тут у spec лежить усе, що треба,
-- щоб відтворити кампанію: поля кампанії, адсети з таргетингом і
-- promoted_object (піксель / апка), оголошення з посиланням на пост
-- Сторінки або описом креатива. Facebook ці дані віддав сам (fb-launch,
-- режим snapshot), ми їх лише зберігаємо.
--
-- Виконати в Supabase → SQL Editor. Повторний запуск нічого не ламає.

create table if not exists public.launch_templates (
  id            bigint generated by default as identity primary key,
  team_name     text not null,
  created_by    uuid not null default auth.uid(),
  name          text not null,
  geo           text,
  note          text,
  source_account text,
  source_campaign text,
  spec          jsonb not null,
  uses          integer not null default 0,
  last_used_at  timestamptz,
  created_at    timestamptz not null default now()
);

create index if not exists launch_templates_team on public.launch_templates (team_name, created_at desc);

alter table public.launch_templates enable row level security;

drop policy if exists "lt_read" on public.launch_templates;
create policy "lt_read" on public.launch_templates
  for select to authenticated using (auth.uid() = created_by);

drop policy if exists "lt_insert" on public.launch_templates;
create policy "lt_insert" on public.launch_templates
  for insert to authenticated with check (auth.uid() = created_by);

drop policy if exists "lt_update" on public.launch_templates;
create policy "lt_update" on public.launch_templates
  for update to authenticated using (auth.uid() = created_by);

drop policy if exists "lt_delete" on public.launch_templates;
create policy "lt_delete" on public.launch_templates
  for delete to authenticated using (auth.uid() = created_by);

revoke all on public.launch_templates from anon;
grant select, insert, update, delete on public.launch_templates to authenticated;
