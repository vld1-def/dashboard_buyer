--
-- «Усі відео й картинки, які вже завантажувала людина, — в одному місці з
-- прев'ю, і вибирати їх, а не заливати знову». Самі файли лежать у
-- сховищі launch-media (LAUNCH_MEDIA.sql); тут — їхній опис: що це, як
-- називається, гео й мова, кадр-мініатюра для відео.
--
-- Виконати в Supabase → SQL Editor. Повторний запуск нічого не ламає.

create table if not exists public.launch_creatives (
  id          bigint generated by default as identity primary key,
  team_name   text not null,
  created_by  uuid not null default auth.uid(),
  path        text not null,
  kind        text not null check (kind in ('video', 'image')),
  name        text,
  size        bigint,
  thumb_path  text,
  geo         text,
  lang        text,
  created_at  timestamptz not null default now(),
  unique (team_name, path)
);

create index if not exists launch_creatives_team on public.launch_creatives (team_name, created_at desc);

alter table public.launch_creatives enable row level security;

drop policy if exists "lc_read" on public.launch_creatives;
create policy "lc_read" on public.launch_creatives
  for select to authenticated using (auth.uid() = created_by);
drop policy if exists "lc_insert" on public.launch_creatives;
create policy "lc_insert" on public.launch_creatives
  for insert to authenticated with check (auth.uid() = created_by);
drop policy if exists "lc_update" on public.launch_creatives;
create policy "lc_update" on public.launch_creatives
  for update to authenticated using (auth.uid() = created_by);
drop policy if exists "lc_delete" on public.launch_creatives;
create policy "lc_delete" on public.launch_creatives
  for delete to authenticated using (auth.uid() = created_by);

revoke all on public.launch_creatives from anon;
grant select, insert, update, delete on public.launch_creatives to authenticated;
