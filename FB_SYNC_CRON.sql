-- ════════════════════════════════════════════════════════════
--  ▶ БЛОК 3 — спільний секрет
--
--  Функції читають його з однієї й тієї ж змінної CRON_SECRET, а
--  секрети Edge Functions спільні на весь проєкт. Тобто якщо ви вже
--  налаштували нічну перевірку доменів — секрет уже є і в сховищі, і
--  у функції, і нового не треба.
--
--  Цей блок саме це й перевіряє. Виконайте його й подивіться на
--  відповідь:
--
--    «ключ уже є, БЛОК 3 пропускаємо» — далі одразу БЛОК 4;
--    «ключа немає» — зробіть те, що написано нижче під блоком.
-- ════════════════════════════════════════════════════════════

select case
  when exists (select 1 from vault.decrypted_secrets
                where name = 'check_domains_cron_key')
  then 'ключ уже є, БЛОК 3 пропускаємо'
  else 'ключа немає — читайте, що робити, одразу під цим блоком'
end as "що далі";

-- ────────────────────────────────────────────────────────────
--  ЯКЩО КЛЮЧА НЕМАЄ
--
--  1. Придумайте його:
--        select encode(gen_random_bytes(24), 'hex');
--
--  2. Supabase → Project Settings → Edge Functions → Secrets →
--     Add new secret:  Name = CRON_SECRET,  Value = цей рядок.
--
--  3. Передеплойте функцію, щоб вона побачила секрет:
--        supabase functions deploy fb-sync
--
--  4. Покладіть той самий рядок у сховище:
--        select vault.create_secret(
--          'ТОЙ-САМИЙ-РЯДОК',
--          'check_domains_cron_key',
--          'Спільний ключ для запуску функцій за розкладом');
--
--  Ім'я лишаємо історичне (check_domains_cron_key), щоб не плодити
--  два однакові секрети під різними назвами. Ключ спільний — це один
--  і той самий CRON_SECRET.
-- ────────────────────────────────────────────────────────────


-- ════════════════════════════════════════════════════════════
--  ▶ БЛОК 4 — ПРОБНИЙ ЗАПУСК, не чекаючи години
--
--  Це рівно те, що робитиме розклад. Виконуйте ОБИДВА запити:
--  перший запускає імпорт, другий показує, чим він скінчився. Між
--  ними зачекайте секунд 20-40 — функція обходить усі кабінети.
--
--  Те саме можна зробити з дашборда, кнопкою: Налаштування →
--  Інтеграції → Facebook → «Sync now». Кнопка робить той самий виклик,
--  тільки від вашого імені й лише по ваших токенах.
-- ════════════════════════════════════════════════════════════

select net.http_post(
  url := (select decrypted_secret from vault.decrypted_secrets
           where name = 'fb_sync_url'),
  headers := jsonb_build_object(
    'content-type', 'application/json',
    'x-cron-key',   (select decrypted_secret from vault.decrypted_secrets
                      where name = 'check_domains_cron_key')),
  body := '{}'::jsonb,
  timeout_milliseconds := 120000);

--  ↓ це через 20-40 секунд, окремим запуском

select status_code, content, created
  from net._http_response
 order by created desc
 limit 3;

-- ────────────────────────────────────────────────────────────
--  ЯК ЧИТАТИ РЕЗУЛЬТАТ
--
--  200 і приблизно такий content — працює:
--      {"cron":true,"tokens":2,"accounts":37,"failed":0,"changed":3,
--       "throttled":false,"more":false,"problems":[]}
--
--      tokens   — скільки токенів обійшли
--      accounts — скільки кабінетів побачили
--      failed   — по скількох Facebook не віддав частину даних
--      changed  — у скількох змінився стан від минулого разу
--      throttled— true означає, що вперлись у ліміт Facebook і вийшли
--                 самі; решту доберемо наступної години
--      problems — що саме не так, по токенах
--
--  Далі подивіться, що приїхало:
--      select account_id, name, status, spend_today,
--             campaigns_active, adsets_active, ads_active, card, synced_at
--        from public.fb_accounts
--       order by spend_today desc nulls last;
--
--  {"tokens":0,…,"note":"no tokens to sync"}
--      токенів у fb_tokens немає. Додайте в дашборді:
--      Налаштування → Інтеграції → Facebook.
--
--  {"accounts":0} і problems про «No ad account is visible»
--      токен живий, прав вистачає, але системному юзеру не видані
--      кабінети: business.facebook.com → Business Settings →
--      System Users → ваш юзер → Add Assets → Ad Accounts.
--
--  problems про «Session has expired»
--      токен відкликали або він протух. У дашборді цей рядок стане
--      червоним і підпишеться сам — видаліть і додайте новий.
--
--  400 «SERVICE_ROLE_KEY is not set»
--      Supabase зазвичай сам кладе SUPABASE_SERVICE_ROLE_KEY у кожну
--      функцію. Якщо у вашому проєкті його немає — додайте секрет
--      SERVICE_ROLE_KEY зі значенням із Project Settings → API →
--      service_role і передеплойте функцію.
--
--  401 {"error":"bad cron key"}
--      секрет у сховищі й секрет у функції не збігаються. Подивитись,
--      що лежить у сховищі (сам секрет не показуємо, досить довжини):
--
--          select name, length(decrypted_secret) as "довжина"
--            from vault.decrypted_secrets
--           where name in ('fb_sync_url', 'check_domains_cron_key');
--
--      Для ключа має бути 48 — стільки дає gen_random_bytes(24) у hex.
--          36 → туди потрапив UUID із відповіді vault.create_secret
--          49 → зайвий пробіл або перенос на кінці
--
--  404
--      функція називається інакше. Перейменування в інтерфейсі не
--      змінює адресу — має бути саме fb-sync.
--
--  Порожньо / жодного рядка
--      запит ще в дорозі, зачекайте і виконайте select ще раз.
-- ────────────────────────────────────────────────────────────


-- ════════════════════════════════════════════════════════════
--  ▶ БЛОК 5 — сам розклад
--
--  Виконуйте лише після того, як БЛОК 4 дав 200.
--
--  Щогодини, на сьомій хвилині. Сьома, а не нульова, навмисно: на
--  початку години в базі й так черга з усього, що ставили «раз на
--  годину», і ставати в неї ще й нам нема потреби.
--
--  Годинний розклад не залежить від переходу на зимовий час — на
--  відміну від нічної перевірки доменів, тут переставляти нічого й
--  ніколи не доведеться.
-- ════════════════════════════════════════════════════════════

select cron.schedule(
  'fb-sync-hourly',
  '7 * * * *',
  $$
  select net.http_post(
    url := (select decrypted_secret from vault.decrypted_secrets
             where name = 'fb_sync_url'),
    headers := jsonb_build_object(
      'content-type', 'application/json',
      'x-cron-key',   (select decrypted_secret from vault.decrypted_secrets
                        where name = 'check_domains_cron_key')),
    body := '{}'::jsonb,
    -- Функція сама стежить за часом і виходить на 110-й секунді,
    -- віддавши more. Двох хвилин їй досить.
    timeout_milliseconds := 120000
  );
  $$);


-- ════════════════════════════════════════════════════════════
--  ЧОМУ САМЕ ГОДИНА, А НЕ ЧАСТІШЕ
--
--  Ліміти Facebook рахуються на застосунок і окремо на кожен
--  рекламний кабінет, і в них зараховуються навіть відмовлені запити.
--  Один прогін коштує приблизно 1 + 4 запити на кабінет: один список
--  і чотири підрахунки всередині. На сорока кабінетах це близько 160
--  запитів на годину — спокійно.
--
--  Якщо впертись у ліміт, Facebook почне відмовляти всьому підряд, і
--  тоді не приїде навіть стан кабінета — тобто саме те, заради чого
--  все робилось. Тому функція, побачивши ліміт, виходить сама й
--  ставить throttled:true, а не довбає далі.
--
--  Хочете частіше — міняйте, але дивіться на throttled у відповідях:
--      select cron.alter_job(
--        (select jobid from cron.job where jobname = 'fb-sync-hourly'),
--        schedule => '*/30 * * * *');
--
--
--  ЧОГО ТУТ НЕМАЄ І НЕ БУДЕ: БІН КАРТКИ
--
--  Marketing API не віддає перших шести цифр. Ніде, жодним полем —
--  це дані платіжної системи. Максимум, що є, це рядок виду
--  «Visa *4242»: тип і останні чотири. Воно й лежить у полі card.
--  Відрізнити одну картку від іншої в парку цього вистачає; шукати
--  бін в інших полях не варто — його там немає.
