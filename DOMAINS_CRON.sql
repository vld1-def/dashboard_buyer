-- ════════════════════════════════════════════════════════════
--  ▶ БЛОК 5 — сам розклад: 05:00, 10:00, 15:00, 20:00
--
--  Виконуйте лише після того, як БЛОК 4 дав 200.
--
--  ЧОМУ ОДНЕ ЗАВДАННЯ, А НЕ ЧОТИРИ. Раніше їх було два — «нічна» і
--  «денна», — і сенс був у тому, що в них різні ролі: одна відкриває
--  день, друга ловить свіже. На чотирьох прогонах цієї різниці вже
--  немає: це просто регулярна перевірка кожні п'ять годин. Чотири
--  окремі завдання довелось би чотири рази правити й чотири рази
--  згадувати, як вони звуться.
--
--  pg_cron живе за UTC. Години задані як рівно GMT+3, без переходів:
--      02:00 UTC = 05:00
--      07:00 UTC = 10:00
--      12:00 UTC = 15:00
--      17:00 UTC = 20:00
--
--  Київ улітку теж UTC+3, тож улітку це рівно ті самі години. Узимку
--  Київ переходить на UTC+2, і перевірка приходитиме на годину раніше
--  за київським — 04:00, 09:00, 14:00, 19:00. Переставляти двічі на
--  рік більше не треба: GMT+3 не переходить, а просили саме його.
--
--  ЩО ЦЕ КОШТУЄ. Запитів до Web Risk стане вдвічі більше, ніж на двох
--  прогонах: кожен прогін витрачає по запиту на домен (поле spent у
--  відповіді). Обмеження на добу у функції немає — скільки прогонів,
--  стільки й запитів.
-- ════════════════════════════════════════════════════════════

--  Спершу прибираємо старі два завдання, якщо вони вже стоять. Без
--  цього вони лишаться поряд із новим, і перевірка ходитиме шість разів
--  на добу, з них двічі — просто так.
--
--  Імена спершу складаємо в масив і лише потім прибираємо: cron.unschedule
--  видаляє рядок із cron.job, а знімати рядки з тієї самої таблиці, яку
--  зараз читаєш, — це покластись на те, як саме Postgres вирішить її
--  обійти. Заодно запит каже вголос, що саме прибрав: якщо не було чого
--  прибирати, це теж відповідь, а не тиша.
do $$
declare
  old_jobs text[] := array(select jobname from cron.job
                            where jobname in ('domains-nightly', 'domains-midday'));
  n text;
begin
  if cardinality(old_jobs) = 0 then
    raise notice 'старих завдань не знайдено — прибирати нічого';
  end if;
  foreach n in array old_jobs loop
    perform cron.unschedule(n);
    raise notice 'прибрано старе завдання: %', n;
  end loop;
end $$;

select cron.schedule(
  'domains-check',
  '0 2,7,12,17 * * *',
  $$
  select net.http_post(
    url := (select decrypted_secret from vault.decrypted_secrets
             where name = 'check_domains_url'),
    headers := jsonb_build_object(
      'content-type', 'application/json',
      'x-cron-key',   (select decrypted_secret from vault.decrypted_secrets
                        where name = 'check_domains_cron_key')),
    body := '{}'::jsonb,
    -- Функція обходить весь список порціями і сама стежить за часом.
    -- Двох хвилин їй досить; обривати раніше — значить лишити хвіст
    -- неперевіреним і не дізнатись про це.
    timeout_milliseconds := 120000
  );
  $$);

