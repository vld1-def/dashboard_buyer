--
--  ЯК КОРИСТУВАТИСЬ ЦИМ ФАЙЛОМ
--  Це не один скрипт, який виконують цілком. Це п'ять блоків, які
--  виконують ПО ЧЕРЗІ в Supabase → SQL Editor: скопіювали блок,
--  натиснули Run, подивились результат, перейшли до наступного.
--
--  Блоки позначені як ▶ БЛОК 1 … ▶ БЛОК 5. Усе інше — коментарі,
--  вони починаються з двох дефісів і нічого не роблять.
--
--  У БЛОЦІ 3 треба замінити два значення на свої. Вони великими
--  літерами, повз них не пройдете.
--
--  Між БЛОКОМ 2 і БЛОКОМ 3 є крок, який робиться не тут, а в
--  інтерфейсі Supabase. Він теж описаний.
--
-- ────────────────────────────────────────────────────────────
--  ЩО ЦЕ ВЗАГАЛІ ТАКЕ
--
--  Щоб не помічати забанений домен через три дні. Перевірка йде сама,
--  без відкритого дашборда, і вранці статуси вже свіжі.
--
--  pg_cron о призначеній годині смикає pg_net, pg_net робить POST на
--  Edge Function check-domains, функція обходить усі домени всіх
--  команд і пише статуси назад.
--
--  ПРО ДОСТУП. О п'ятій ранку ніхто не залогінений, токена людини
--  взяти нізвідки, тож RLS від нього не порахуєш. Тому у функції є
--  окремий вхід: заголовок x-cron-key зі спільним секретом. Звіривши
--  його, функція бере ключ сервісної ролі — і лише тоді бачить усе.
--
--  У базі лежить тільки CRON_SECRET, який уміє рівно одне: запустити
--  перевірку доменів. Ключ сервісної ролі вміє все і лишається в
--  секретах функції, у базу не потрапляє взагалі.
-- ════════════════════════════════════════════════════════════


-- ════════════════════════════════════════════════════════════
--  ▶ БЛОК 1 — розширення
--
--  Саме через це «relation net._http_response does not exist»:
--  таблиця з відповідями з'являється лише після pg_net.
--  Виконайте ці два рядки першими.
-- ════════════════════════════════════════════════════════════

create extension if not exists pg_cron;
create extension if not exists pg_net;


-- ════════════════════════════════════════════════════════════
--  ▶ БЛОК 2 — придумати секрет
--
--  Виконайте і СКОПІЮЙТЕ результат — довгий рядок із літер і цифр.
--  Він знадобиться двічі: в інтерфейсі Supabase і в БЛОЦІ 3.
-- ════════════════════════════════════════════════════════════

select encode(gen_random_bytes(24), 'hex') as "скопіюйте цей рядок";


-- ════════════════════════════════════════════════════════════
--  ⚠ КРОК МІЖ БЛОКАМИ — робиться НЕ тут
--
--  1. Supabase → Project Settings → Edge Functions → Secrets
--     Add new secret:
--        Name:  CRON_SECRET
--        Value: рядок із БЛОКУ 2
--
--  2. Задеплойте функцію заново, щоб вона побачила новий секрет:
--        supabase functions deploy check-domains
--
--  Ключ сервісної ролі окремо додавати НЕ треба: Supabase сам кладе
--  SUPABASE_SERVICE_ROLE_KEY у кожну Edge Function. Якщо у вашому
--  проєкті його немає — додайте секрет SERVICE_ROLE_KEY зі значенням
--  із Project Settings → API → service_role.
--
--  Поки цього не зроблено, БЛОКИ 3-5 виконувати марно: функція
--  відповість 400 і скаже, що розклад не налаштовано.
-- ════════════════════════════════════════════════════════════


-- ════════════════════════════════════════════════════════════
--  ▶ БЛОК 3 — куди стукати і чим
--
--  ЗАМІНІТЬ ДВА ЗНАЧЕННЯ:
--    ВАШ-ПРОЄКТ            → Project Settings → API → Project URL
--                            (там буде https://abcdefgh.supabase.co —
--                             потрібна тільки частина abcdefgh)
--    СЮДИ-СЕКРЕТ-З-БЛОКУ-2 → рівно той рядок, що ви поклали
--                            в CRON_SECRET
--
--  Кладемо в сховище, а не в текст розкладу: у cron.job рядок лежав
--  би відкритим, і будь-який select його показав би.
--
--  Якщо виконати цей блок удруге, буде помилка про дублікат імені —
--  секрет уже створено. Щоб ЗМІНИТИ значення, дивіться БЛОК 5.
-- ════════════════════════════════════════════════════════════

select vault.create_secret(
  'https://ВАШ-ПРОЄКТ.supabase.co/functions/v1/check-domains',
  'check_domains_url',
  'Нічна перевірка доменів: адреса функції');

select vault.create_secret(
  'СЮДИ-СЕКРЕТ-З-БЛОКУ-2',
  'check_domains_cron_key',
  'Нічна перевірка доменів: спільний секрет');


-- ════════════════════════════════════════════════════════════
--  ▶ БЛОК 4 — перевірити, що працює, не чекаючи ранку
--
--  Це той самий запит, який щоночі робитиме розклад. Виконайте його
--  руками зараз: якщо він спрацює, спрацює й розклад.
--
--  Виконуйте ОБИДВА запити: перший запускає перевірку, другий
--  показує, чим вона скінчилась. Між ними зачекайте секунд 20-30 —
--  функція обходить усі домени, це не миттєво.
-- ════════════════════════════════════════════════════════════

select net.http_post(
  url := (select decrypted_secret from vault.decrypted_secrets
           where name = 'check_domains_url'),
  headers := jsonb_build_object(
    'content-type', 'application/json',
    'x-cron-key',   (select decrypted_secret from vault.decrypted_secrets
                      where name = 'check_domains_cron_key')),
  body := '{}'::jsonb,
  timeout_milliseconds := 120000);

--  ↓ це через 20-30 секунд, окремим запуском

select status_code, content, created
  from net._http_response
 order by created desc
 limit 3;

-- ────────────────────────────────────────────────────────────
--  ЯК ЧИТАТИ РЕЗУЛЬТАТ
--
--  200 і приблизно такий content — усе працює:
--      {"cron":true,"checked":128,"more":false,"flags":"web-risk+dns",
--       "spent":128,"changed":2,"worse":[…]}
--
--      checked — скільки доменів пройшли
--      spent   — скільки запитів Web Risk це коштувало
--      worse   — що саме погіршилось; звідси потім піде Telegram
--
--  На сторінці Domains колонка Checked має показати свіжий час.
--
--  401 {"error":"bad cron key"}
--      секрет у сховищі й секрет у функції не збігаються.
--
--  400 «scheduled run is not configured»
--      у функції немає CRON_SECRET, або її не перезадеплоєно після
--      того, як ви його додали.
--
--  404
--      функція називається інакше. Перейменування в інтерфейсі не
--      змінює адресу — має бути саме check-domains.
--
--  Порожньо / жодного рядка
--      запит ще в дорозі, зачекайте і виконайте select ще раз.
-- ────────────────────────────────────────────────────────────


-- ════════════════════════════════════════════════════════════
--  ▶ БЛОК 5 — сам розклад
--
--  Виконуйте лише після того, як БЛОК 4 дав 200.
--
--  pg_cron живе за UTC, а не за київським часом:
--      '0 2 * * *'  = 05:00 у Києві ВЛІТКУ  (UTC+3, кінець бер. — кінець жовт.)
--      '0 3 * * *'  = 05:00 у Києві ВЗИМКУ  (UTC+2)
--
--  Тобто двічі на рік цей рядок треба переставити — команда нижче.
--  Не переставите — раз на пів року перевірка просто почнеться о
--  четвертій або о шостій. Нічого не зламається.
-- ════════════════════════════════════════════════════════════

select cron.schedule(
  'domains-nightly',
  '0 2 * * *',
  $$
  select net.http_post(
    url := (select decrypted_secret from vault.decrypted_secrets
             where name = 'check_domains_url'),
    headers := jsonb_build_object(
      'content-type', 'application/json',
      'x-cron-key',   (select decrypted_secret from vault.decrypted_secrets
                        where name = 'check_domains_cron_key')),
    body := '{}'::jsonb,
    -- Функція обходить весь список порціями і сама стежить за часом.
    -- Двох хвилин їй досить; обривати раніше — значить лишити хвіст
    -- неперевіреним і не дізнатись про це.
    timeout_milliseconds := 120000
  );
  $$);


