-- ============================================================
--  НІЧНА ПЕРЕВІРКА ДОМЕНІВ — щодня о 05:00
-- ============================================================
--
--  Навіщо: щоб не помічати забанений домен через три дні. Перевірка
--  йде сама, без відкритого дашборда, і вранці статуси вже свіжі.
--
--  Як це влаштовано: pg_cron о призначеній годині смикає pg_net,
--  pg_net робить POST на Edge Function check-domains, функція обходить
--  усі домени всіх команд і пише статуси назад.
--
--  ПРО ДОСТУП. О пʼятій ранку ніхто не залогінений, токена людини
--  взяти нізвідки, тож RLS від нього не порахуєш. Тому у функції є
--  окремий вхід: заголовок x-cron-key зі спільним секретом. Звіривши
--  його, функція бере ключ сервісної ролі — і лише тоді бачить усе.
--
--  У розкладі лежить CRON_SECRET, який уміє рівно одне: запустити
--  перевірку доменів. Ключ сервісної ролі вміє все і лишається в
--  секретах функції, у базу не потрапляє взагалі.
--
--  Порядок: спершу КРОК 0 (секрет у функції), потім решта тут.
-- ============================================================


-- ────────────────────────────────────────────────────────────
--  КРОК 0. Секрет для функції  (робиться НЕ тут, а в Supabase)
-- ────────────────────────────────────────────────────────────
--  Спочатку придумайте довгий випадковий рядок. Можна прямо звідси:
--
--      select encode(gen_random_bytes(24), 'hex');
--
--  Скопіюйте результат і додайте його в
--      Supabase → Project Settings → Edge Functions → Secrets
--      Name:  CRON_SECRET
--      Value: той самий рядок
--
--  Ключ сервісної ролі окремо додавати НЕ треба: Supabase сам кладе
--  SUPABASE_SERVICE_ROLE_KEY у кожну Edge Function. Якщо у вашому
--  проєкті його чомусь немає — додайте секрет SERVICE_ROLE_KEY зі
--  значенням із Project Settings → API → service_role.
--
--  Далі задеплойте функцію заново, щоб вона підхопила новий секрет:
--      supabase functions deploy check-domains
-- ────────────────────────────────────────────────────────────


-- ────────────────────────────────────────────────────────────
--  КРОК 1. Розширення
-- ────────────────────────────────────────────────────────────
create extension if not exists pg_cron;
create extension if not exists pg_net;


-- ────────────────────────────────────────────────────────────
--  КРОК 2. Куди стукати і чим
-- ────────────────────────────────────────────────────────────
--  Кладемо в сховище, а не в текст розкладу: у cron.job рядок лежав би
--  відкритим, і будь-який select його показав би.
--
--  ЗАМІНІТЬ обидва значення на свої.
--    - у першому: адреса проєкту (Project Settings → API → Project URL)
--    - у другому: рівно той рядок, що ви поклали в CRON_SECRET
-- ────────────────────────────────────────────────────────────
select vault.create_secret(
  'https://ВАШ-ПРОЄКТ.supabase.co/functions/v1/check-domains',
  'check_domains_url',
  'Нічна перевірка доменів: адреса функції');

select vault.create_secret(
  'СЮДИ-ТОЙ-САМИЙ-CRON-SECRET',
  'check_domains_cron_key',
  'Нічна перевірка доменів: спільний секрет');


-- ────────────────────────────────────────────────────────────
--  КРОК 3. Розклад
-- ────────────────────────────────────────────────────────────
--  pg_cron живе за UTC, а не за київським часом.
--
--      '0 2 * * *'  = 05:00 у Києві влітку (UTC+3, кінець березня — кінець жовтня)
--      '0 3 * * *'  = 05:00 у Києві взимку (UTC+2)
--
--  Тобто двічі на рік цей рядок треба переставити — унизу є готова
--  команда. Якщо переставляти не хочеться, лишіть як є: раз на пів
--  року перевірка просто почнеться о четвертій або о шостій.
-- ────────────────────────────────────────────────────────────
select cron.schedule(
  'domains-nightly',
  '0 2 * * *',
  $$
  select net.http_post(
    url := (select decrypted_secret from vault.decrypted_secrets
             where name = 'check_domains_url'),
    headers := jsonb_build_object(
      'content-type', 'application/json',
      'x-cron-key',   (select decrypted_secret from vault.decrypted_secrets
                        where name = 'check_domains_cron_key')),
    body := '{}'::jsonb,
    -- Функція обходить весь список порціями і сама стежить за часом.
    -- Двох хвилин їй досить; обривати раніше — значить лишити хвіст
    -- неперевіреним і не дізнатись про це.
    timeout_milliseconds := 120000
  );
  $$);


-- ────────────────────────────────────────────────────────────
--  ПЕРЕВІРКА, ЩО ВСЕ ПРАЦЮЄ
-- ────────────────────────────────────────────────────────────
--  Розклад на місці:
--      select jobid, jobname, schedule, active from cron.job;
--
--  Чи запускалось і чим скінчилось:
--      select jobid, status, return_message, start_time
--        from cron.job_run_details
--       order by start_time desc limit 10;
--
--  Що саме відповіла функція — тут найкорисніше:
--      select status_code, content, created
--        from net._http_response
--       order by created desc limit 5;
--
--  Очікувана відповідь:
--      {"cron":true,"checked":128,"more":false,"flags":"web-risk+dns",
--       "spent":128,"changed":2,"worse":[…]}
--
--    checked — скільки доменів пройшли
--    spent   — скільки запитів Web Risk це коштувало
--    worse   — що саме погіршилось за ніч; звідси потім піде Telegram
--
--  Якщо status_code = 401 і {"error":"bad cron key"} — секрет у сховищі
--  і секрет у функції не збігаються.
--  Якщо 400 і «scheduled run is not configured» — у функції немає
--  CRON_SECRET, або вона не перезадеплоєна після його додавання.
--
--  Не чекати до ранку: виконайте тіло розкладу руками — той самий
--  select net.http_post(...) з КРОКУ 3, окремо від cron.schedule. За
--  кілька секунд відповідь зʼявиться в net._http_response, а на
--  сторінці Domains колонка Checked покаже свіжий час.


