/* ═══════════ БАН АПКИ — ЗА ТИМ, ЩО СКАЗАВ PLAY ═══════════

   «Бани апок став сразу як бачиш помилки а не за другим проходом».

   Двопрохідність заводили не від обережності взагалі, а через те, що
   Play відмовляє з різних причин: ліміт частоти, геоблок, власні
   збої. Забанена воронка зникає зі списку прілок, тож хибний бан
   ховає робочу апку.

   Але «помилка» — не одне й те саме слово для всіх випадків, і саме
   на цьому тепер проходить межа:

     • 429, 5xx, геоблок, тайм-аут — probe віддає 'unknown', стану не
       чіпає взагалі. Сюди другий прохід і не потрібен — тут його
       ніколи й не було;
     • 404 — Play сказав прямо: сторінки немає. Бан з першого разу;
     • 200 без ознак апки — заглушка чи сторінка згоди. Тут двох
       проходів і стосувалось питання, і тут вони лишаються.

   Стенд читає саму функцію: гілка рішення одна, і перевіряти її треба
   там, де вона написана. */
import fs from 'node:fs';
import { checks } from './_harness.mjs';

const { ok, done } = checks();
const FN = fs.readFileSync('supabase/functions/check-apps/index.ts', 'utf8');

/* ── 1. МОВЧАННЯ PLAY ДО РІШЕННЯ НЕ ДОХОДИТЬ ──
   Якщо колись 429 чи 5xx почнуть віддавати 'gone', швидкий бан
   перетвориться на те, від чого двопрохідність і рятувала. */
ok('429 лишається unknown',
  /res\.status === 429[\s\S]{0,160}state: 'unknown'/.test(FN), '429 → unknown');
ok('5xx лишається unknown',
  /res\.status >= 500[\s\S]{0,200}state: 'unknown'/.test(FN), '5xx → unknown');
ok('геоблок лишається unknown',
  /not available in your country[\s\S]{0,220}state: 'unknown'/.test(FN), 'geo → unknown');
ok('тайм-аут лишається unknown',
  /catch \(e\)[\s\S]{0,260}state: 'unknown'/.test(FN), 'timeout → unknown');
ok('а unknown не чіпає ні стану, ні дня',
  /Ми не дізнались[\s\S]{0,220}unknown\+\+/.test(FN), 'unknown → nothing');

/* ── 2. ГІЛКА РІШЕННЯ ── */
const gone = FN.slice(FN.lastIndexOf("} else if (v.state === 'gone') {"),
                      FN.indexOf('/* Ми не дізнались'));
ok('рішення спирається саме на 404',
  /const sure = v\.code === 404;/.test(gone), gone.slice(0, 80));
/* Головне в цій зміні. */
ok('по 404 бан ставиться одразу',
  /if \(sure && r\.status !== 'ban'\)[\s\S]{0,200}patch\.status = 'ban'/.test(gone), 'sure → ban');
ok('і в нотатці сказано, що це було 404',
  /404 від Play, поставлено ban одразу/.test(gone), 'note');
/* Коли апка зникла — питання окреме від того, скільки проходів на це
   пішло, і відповідь на нього потрібна в обох випадках. */
ok('день зникнення пишеться й у швидкому випадку',
  /sure && r\.status !== 'ban'[\s\S]{0,120}app_gone_since = r\.app_gone_since \|\| at/.test(gone),
  'app_gone_since');
/* Уже забанену не баним удруге: інакше кожен нічний обхід дописував
   би ту саму воронку в список щойно забанених. */
ok('уже забанену вдруге не рахують',
  /\} else if \(sure\) \{/.test(gone), 'else if (sure)');

/* ── 3. 200 БЕЗ ОЗНАК АПКИ — ДВА ПРОХОДИ, ЯК І БУЛО ── */
ok('перша невдача без 404 стану не чіпає',
  /!r\.app_gone_since[\s\S]{0,320}перша невдача без 404, стан не змінено/.test(gone), 'first');
ok('а друга поспіль ставить ban',
  /друга перевірка поспіль, поставлено ban/.test(gone), 'second');

/* ── 4. ЗНЯТТЯ БАНУ НЕ ЗМІНИЛОСЬ ──
   Бан, поставлений людиною, робот знімати не має права: вона могла
   забанити апку з причини, якої в Play не видно. */
ok('робот знімає лише свій бан',
  /r\.status === 'ban' && r\.app_banned_by === 'robot'/.test(FN), 'app_banned_by');
ok('і швидкий бан теж підписаний роботом',
  (gone.match(/app_banned_by = 'robot'/g) || []).length === 2, 'robot x2');

/* ── 4б. ПЕРЕВІРКА РУКАМИ ТЕПЕР СТАВИТЬ БАН ──

   «якщо руками перевіряти пише ОК, але в повідомленні пише що бан,
   насправді пріла в бані, статус не міняється».

   Так і було, і це було задумано: бан прибирає воронку зі списку
   прілок, тож хай вирішує нічний обхід. На практиці обхід не ходив —
   і екран показував дві протилежні речі одночасно: нотатку «апки
   немає» і зелену пігулку поруч. */
const manual = FN.slice(FN.indexOf('═══ ВХІД ЛЮДИНИ'),
                        FN.indexOf('═══ ВХІД РОЗКЛАДУ'));
ok('ручний вхід знайдено', manual.length > 400);
ok('«немає» з перевірки руками ставить бан',
  /patch\.status = 'ban';/.test(manual), manual.slice(0, 60));
/* Робочий бан, а не людський: інакше обхід не зніме його, коли апка
   відкриється, і вона лишиться вимкненою назавжди. */
ok('і підписаний роботом, щоб обхід міг його зняти',
  /patch\.app_banned_by = 'robot';/.test(manual));
ok('апка на місці — свій бан знімається тут-таки',
  /patch\.status = 'active';/.test(manual) && /app_banned_by = null/.test(manual));
/* 429, 5xx і таймаут не є відповіддю Play: там статус не чіпаємо, і
   це єдина обережність, яка тут була доречна. */
ok('невідоме статусу не чіпає',
  !/unknown[\s\S]{0,120}patch\.status/.test(manual), 'unknown');
/* Невдалий запис — не «перевірено». Доти він мовчав, і людина бачила
   «апки немає», не знаючи, що в базі не змінилось нічого. */
ok('невдалий запис у базу названо вголос', /save_error/.test(manual), 'save_error');
ok('сторінка каже, що саме сталось зі статусом', (() => {
  const F = fs.readFileSync('Form.html', 'utf8');
  return /статус змінено на/.test(F) && /бан знято/.test(F) && /save_error/.test(F);
})(), 'Form.html');

/* ── 5. ВЕРСІЯ ── */
/* Не прибиваємо до конкретної дати: версія росте, і піднімати її не
   має ламати перевірку про щось інше. */
const ver = (FN.match(/FN_VERSION = '([^']+)'/) || [])[1] || '';
ok('версію функції піднято не нижче 2026-11-06', ver >= '2026-11-06', ver);

await done(null, null, []);
