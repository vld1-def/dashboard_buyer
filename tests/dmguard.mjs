/* ═══════════ 403 — ЦЕ НЕ МЕРТВИЙ ДОМЕН ═══════════

   Домени, які чудово відкриваються в браузері, щоранку приходили як
   зламані. Причина в одному рядку: будь-який 4xx, крім 404, ішов у
   notfound.

   А 403 означає рівно протилежне. DNS розвʼязався, TLS потиснув
   руку, сервер ВІДПОВІВ — і відмовив саме нам. Для лендінга це
   нормальний робочий стан: Cloudflare відсікає все, що не схоже на
   людину, а клоакінг віддає сторінку лише своєму трафіку з
   потрібного гео. Запит із серверної адреси туди не потрапляє за
   визначенням.

   Стенд читає саме рішення з файлу функції й виконує його: це той
   код, через який уночі будили людину. */
import fs from 'node:fs';
import { checks } from './_harness.mjs';

const { ok, done } = checks();
const FN = fs.readFileSync('supabase/functions/check-domains/index.ts', 'utf8');

const m = FN.match(/const GUARDED[\s\S]*?\nfunction verdictOf\([\s\S]*?\n\}/);
ok('рішення про код відповіді знайдено у файлі', !!m);
const verdict = m
  ? new Function(m[0].replace(/: Verdict/g, '').replace(/(\w+): number/g, '$1')
      + '; return verdictOf;')()
  : () => ({ status: 'missing' });

const st = c => verdict(c).status;

ok('200 — працює', st(200) === 'ok');
ok('301 — працює: редирект це теж відповідь', st(301) === 'ok');
/* Саме той випадок, через який усе й почалось. */
ok('403 більше не «сторінки немає»', st(403) === 'guarded');
ok('401 так само', st(401) === 'guarded');
/* 429 — нас просто попросили не частити. Домен при цьому живий. */
ok('429 — не поломка, а обмеження частоти', st(429) === 'guarded');
ok('451 — юридичне блокування теж не падіння', st(451) === 'guarded');
/* А це вже про домен, а не про нас: сервер каже, що сторінки немає. */
ok('404 лишається notfound', st(404) === 'notfound');
ok('410 — теж notfound', st(410) === 'notfound');
ok('500 — down', st(500) === 'down');
ok('503 — down', st(503) === 'down');
ok('код відповіді зберігається як є', verdict(403).status_code === 403);

/* Мережева відмова з одного разу — не вирок: обірване зʼєднання з
   сотні це мережа, а домен, записаний у зламані, йде в телеграм. */
ok('на мережеву відмову є друга спроба',
  /attempt < 2/.test(FN) && /break;\s+\/\/ на другий заход/.test(FN));
ok('друга спроба не йде впритул', /setTimeout\(r, 800\)/.test(FN));
/* Повторюємо лише мережеву відмову: код відповіді другого разу дасть
   той самий, і зайвий запит нічого не додасть. */
ok('код відповіді другий раз не перепитується',
  /return verdictOf\(res\.status\);/.test(FN));

/* Тривогу новий стан не здіймає: домену нічого не бракує. */
const DM = fs.readFileSync('build/domains.js', 'utf8');
ok('guarded видно окремою плиткою', /guarded:\s*\{ label: 'Shields up'/.test(DM));
ok('і він стоїть у порядку станів', /DM_ORDER = \[[^\]]*'guarded'/.test(DM));
ok('але не серед проблемних',
  !/DM_BAD = \[[^\]]*'guarded'/.test(DM) && /DM_BAD = \['danger', 'notfound', 'down'\]/.test(DM));
/* Дивимось у сам обʼєкт TG_WHAT, а не поруч: одразу під ним стоїть
   коментар, який пояснює, чому guarded там немає — і збіг по сусідству
   ловив би саме пояснення. */
const tgWhat = (FN.match(/const TG_WHAT[^{]*\{([\s\S]*?)\}/) || [])[1] || '';
ok('і в телеграм про нього не пишуть',
  !!tgWhat && !/guarded/.test(tgWhat) && /danger/.test(tgWhat));

await done(null, null, []);
