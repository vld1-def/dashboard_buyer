-- «додаємо мою ідею (іконка на відео) + бібліотека хуків та кінцівок».
-- Файли лежать у сховищі launch-media, у папці команди (team/uq/…), опис —
-- тут. role: hook — початок, ending — кінцівка, overlay — картинка/іконка.
create table if not exists public.uq_clips (
  id          bigint generated by default as identity primary key,
  team_name   text not null,
  created_by  uuid not null default auth.uid(),
  role        text not null check (role in ('hook', 'ending', 'overlay')),
  kind        text not null check (kind in ('video', 'image')),
  path        text not null,
  name        text,
  size        bigint,
  created_at  timestamptz not null default now(),
  unique (team_name, path)
);
create index if not exists uq_clips_team on public.uq_clips (team_name, role, created_at desc);
alter table public.uq_clips enable row level security;
drop policy if exists "uqc_read" on public.uq_clips;
create policy "uqc_read" on public.uq_clips for select to authenticated using (auth.uid() = created_by);
drop policy if exists "uqc_insert" on public.uq_clips;
create policy "uqc_insert" on public.uq_clips for insert to authenticated with check (auth.uid() = created_by);
drop policy if exists "uqc_delete" on public.uq_clips;
create policy "uqc_delete" on public.uq_clips for delete to authenticated using (auth.uid() = created_by);
revoke all on public.uq_clips from anon;
grant select, insert, delete on public.uq_clips to authenticated;
