-- ── КРОК 1. Свій user_id ─────────────────────────────────────────────
--
-- Підставте свою пошту. Якщо рядків більше за один — у вас кілька
-- акаунтів, і далі треба брати id того, під яким ви заходите в дашборд.

select id, email, created_at
from auth.users
where email = 'ВАША@ПОШТА';


-- ── КРОК 2. Що саме піде ─────────────────────────────────────────────
--
-- ОБОВ'ЯЗКОВО подивіться цей список перед видаленням.
--
-- Запит навмисно НЕ фільтрує по власнику: він показує всі рядки з цими
-- номерами й поруч — чиї вони. Так одразу видно, чи немає серед них
-- кабінета іншого баєра. Фільтр по created_by стоїть нижче, у самому
-- видаленні, тож чуже не піде навіть якщо ви його тут побачите.

with mine as (
  select id from auth.users where email = 'ВАША@ПОШТА'
),
gone as (
  select * from unnest(array[
    '1059930743439200',
    '1426500685612301',
    '1629779721461079',
    '1267723482194515',
    '26622056184118131',
    '1073574788583564',
    '1839069687503118',
    '1729232005128002'
  ]) as t(account_id)
)
select
  a.account_id,
  a.name,
  a.status,
  a.team_name,
  u.email                                   as owner,
  (a.created_by = (select id from mine))    as is_mine,
  a.token_id,                               -- null = токен уже видалено
  a.missing_since,                          -- null = жоден прогін не позначав
  a.spend_today,
  a.synced_at
from public.fb_accounts a
join gone g  on g.account_id = a.account_id
left join auth.users u on u.id = a.created_by
order by is_mine desc, a.account_id;


-- ── КРОК 3. Видалити ─────────────────────────────────────────────────
--
-- ЦЕ ОДИН ЗАПИТ, І ВІН УЖЕ АТОМАРНИЙ. Усі чотири видалення живуть у
-- CTE одного оператора, тож або проходить усе, або нічого — окремих
-- begin/commit тут не треба, і писати їх було б навіть гірше: редактор
-- Supabase виконує скрипт цілком, і «подивіться на числа й вирішіть»
-- перетворилось би на ілюзію вибору. Дивитись треба на КРОЦІ 2, до
-- того як щось зникло.
--
-- Кожне видалення обмежене вашим created_by. Порядок від дрібного до
-- головного — щоб не лишилось чисел по кабінету, якого вже немає.
--
-- Якщо якоїсь із таблиць у вашій базі ще немає (fb_ad_today приходить
-- із FB_RULES.sql, fb_cabinet_pages — із FB_SYNC.sql), запит просто
-- відмовить із назвою тієї таблиці й НІЧОГО не видалить: один оператор,
-- усе або нічого. Тоді приберіть відповідний блок d2/d3 і виконайте
-- знову.

with mine as (
  select id from auth.users where email = 'ВАША@ПОШТА'
),
gone as (
  select * from unnest(array[
    '1059930743439200',
    '1426500685612301',
    '1629779721461079',
    '1267723482194515',
    '26622056184118131',
    '1073574788583564',
    '1839069687503118',
    '1729232005128002'
  ]) as t(account_id)
),
-- Денні витрати по цих кабінетах. Без цього вони лишились би в історії
-- й далі потрапляли б у суми за період — кабінета немає, а гроші є.
d1 as (
  delete from public.fb_spend_daily
   where created_by = (select id from mine)
     and account_id in (select account_id from gone)
  returning 1
),
-- Знімок оголошень: із нього живуть правила й таблиця кампаній.
d2 as (
  delete from public.fb_ad_today
   where created_by = (select id from mine)
     and account_id in (select account_id from gone)
  returning 1
),
-- Сторінки, прив'язані до кабінета.
d3 as (
  delete from public.fb_cabinet_pages
   where created_by = (select id from mine)
     and account_id in (select account_id from gone)
  returning 1
),
-- І сам кабінет.
d4 as (
  delete from public.fb_accounts
   where created_by = (select id from mine)
     and account_id in (select account_id from gone)
  returning 1
)
select
  (select count(*) from d1) as spend_days_deleted,
  (select count(*) from d2) as ad_rows_deleted,
  (select count(*) from d3) as pages_deleted,
  (select count(*) from d4) as cabinets_deleted;

-- Числа у відповіді — звіт про зроблене. cabinets_deleted має
-- дорівнювати кількості ваших кабінетів зі списку КРОКУ 2 (стовпчик
-- is_mine = true).
--
