-- ════════════════════════════════════════════════════════════
--  ▶ СТАН АПКИ: ACTIVE / BAN
--
--  ЗАЧИМ. Апку банять — і далі вона лежить у списку рівно так само, як
--  живі. Шаблон під неї вибирають очима, нагадати про бан нічому, і
--  неймінг забаненої апки спокійно їде в кабінет. Видаляти воронку
--  натомість не можна: на її KTID тримається вся залита статистика,
--  і без рядка вона стає «Unknown (CS11003)» у кожному звіті за
--  минулі місяці.
--
--  Тому стан, а не видалення. Забанена воронка лишається в базі й у
--  таблиці KTID Mappings (там її й знімають з бану), але зі списку
--  апок у Прілках зникає: саме там з неї роблять новий шаблон.
--
--  ЧОМУ DEFAULT 'active', А НЕ NULL. Порожній стан довелось би читати
--  як «невідомо», і кожне місце, яке питає «ця апка жива?», мало б
--  власну догадку. Усе вже заведене — живе, поки не сказали інше.
--
--  Виконати: Supabase → SQL Editor → Run. Один раз.
-- ════════════════════════════════════════════════════════════

alter table public.funnels_mapping
  add column if not exists status text default 'active';

-- Рядки, заведені до цієї міграції, стану не мають — а читаються вони
-- як живі, тож і в базі мусить стояти те саме слово. Інакше перше ж
-- «показати лише активні» сховало б усе, що завели раніше.
update public.funnels_mapping set status = 'active' where status is null;

-- Стан — слово з двох, і слідкувати за цим має база: на екрані
-- помилку видно, в API — ні.
alter table public.funnels_mapping
  drop constraint if exists funnels_mapping_status_chk;
alter table public.funnels_mapping
  add constraint funnels_mapping_status_chk
  check (status is null or status in ('active', 'ban'));


-- ════════════════════════════════════════════════════════════
--  ▶ ЗВІТ — що вийшло
-- ════════════════════════════════════════════════════════════
select status, count(*) filter (where is_app) as apps, count(*) as all_funnels
from public.funnels_mapping
group by status;
