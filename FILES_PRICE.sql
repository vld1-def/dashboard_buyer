--
-- «коли редагую файл — вказую ціну, наприклад 10$, і якщо там 10
-- кабінетів, то вже зрозуміло, яка ціна одного».
--
--   price — скільки заплатили за весь файл, у доларах;
--   units — скільки в ньому одиниць: кабінетів (@мітки) або рядків з
--           акаунтами. Сторінка рахує це сама, коли файл відкривають, а
--           у формі редагування число можна поправити руками.
--
-- Ціна одиниці = price / units — її показують список файлів і підказка
-- над @кабінетом. Окремо не зберігається: інакше розійшлася б із
-- price чи units після першої ж правки.
--
-- Виконати в Supabase → SQL Editor. Повторний запуск нічого не ламає.

-- units_fixed — кількість поправили руками. Тоді файл її не перебиває;
-- інакше units перераховується щоразу, як файл відкривають чи
-- зберігають: дописав ще кабінети — ціна одного сама стала меншою.

alter table public.file_links
  add column if not exists price numeric,
  add column if not exists units integer,
  add column if not exists units_fixed boolean not null default false;
