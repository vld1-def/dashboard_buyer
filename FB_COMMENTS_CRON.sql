--      id, 'https://ВАШ-ПРОЄКТ.supabase.co/functions/v1/fb-comments')
--      from vault.secrets where name = 'fb_comments_url';
--
--  ВАШ-ПРОЄКТ береться з Project Settings — API — Project URL: там
--  буде https://abcdefgh.supabase.co, потрібна частина abcdefgh.
--
--  Після цього запустіть пробний запуск ще раз — error_msg має
--  зникнути, а status_code стати 200.
-- ────────────────────────────────────────────────────────────


-- ════════════════════════════════════════════════════════════
--  ▶ БЛОК 3 — ПРОБНИЙ ЗАПУСК, не чекаючи розкладу
--
--  Виконайте ОБИДВА запити: перший запускає обхід, другий показує, чим
--  він скінчився. Між ними зачекайте секунд 20-60.
-- ════════════════════════════════════════════════════════════

select net.http_post(
  url := (select decrypted_secret from vault.decrypted_secrets
           where name = 'fb_comments_url'),
  headers := jsonb_build_object(
    'content-type', 'application/json',
    'x-cron-key',   (select decrypted_secret from vault.decrypted_secrets
                      where name = 'check_domains_cron_key')),
  body := '{"action":"scan"}'::jsonb,
  -- Функція сама стежить за часом і виходить на 100-й секунді.
  timeout_milliseconds := 120000
) as request_id;


-- Другим запитом — що відповіла функція.
--
-- Без жодних перетворень навмисно: у pg_net колонка content у різних
-- версіях то text, то bytea, і будь-яке приведення типу працює рівно
-- на одній із них. Читається воно й так, а запит, який залежить від
-- версії розширення, у інструкції не має права стояти.
-- error_msg і timed_out тут не для краси. Коли запит не дійшов зовсім,
-- status_code і content порожні, і без цих двох колонок видно лише те,
-- що «щось не так» — а причина лежить саме в них.
select status_code, error_msg, timed_out, content, created
  from net._http_response
 order by created desc
 limit 3;

--  ЩО МАЄ БУТИ
--    scanned  — скільки кабінетів обійшли цього разу
--    posts    — скільки постів під ними подивились
--    comments — скільки коментарів прочитали всього
--    found    — скільки з них нові
--    hidden   — скільки з нових сховали
--    telegram — «N sent» або причина, чому не надіслали
--
--  posts: 0 при scanned більше нуля — кабінети є, а постів під ними
--  немає: жодне оголошення не веде на пост Сторінки, тож і коментарів
--  бути не може. Це не помилка, але й не «все гаразд»: дивитись
--  просто не було на що.
--
--  comments більше нуля, а found: 0 — подивились як слід, нового
--  немає. Саме так і має виглядати спокійний прогін.
--
--  Перший запуск майже напевно дасть found: 0 — і це правильно
--  (див. «ПЕРШИЙ ОБХІД» угорі). Запустіть ще раз за півгодини.
--
--  «the comment columns are missing» — не виконано блок alter table
--  з FB_SYNC.sql.
--
--  ЯКЩО status_code І content ПОРОЖНІ
--  Відповіді не було зовсім, і дивитись треба в error_msg:
--
--    timed_out = true — не дочекались. У функції сто секунд, тож
--      найчастіше це означає, що вона не запустилась, а не що довго
--      працювала;
--
--    «Could not resolve host» — у сховищі крива адреса. Перевірте
--      БЛОКОМ 1, що вона взагалі є, і подивіться на неї очима:
--        select decrypted_secret from vault.decrypted_secrets
--         where name = 'fb_comments_url';
--
--    «Connection refused» або 404 — функції за цією адресою немає:
--      не задеплоєна або задеплоєна в інший проєкт.
--
--  І ОДРАЗУ ПЕРЕВІРТЕ ЩОГОДИННИЙ fb-sync. Він ходить на сьомій
--  хвилині й пише в ту саму таблицю. Якщо в нього так само порожньо D
--  справа не в коментарях: з бази не виходить ЖОДЕН запит, і
--  щогодинна синхронізація теж давно не працює. Помітити це раніше
--  було ніяк: кнопка Sync now у дашборді ходить із браузера, іншим
--  шляхом, і від цього не залежить.


-- ════════════════════════════════════════════════════════════
--  ▶ БЛОК 4 — сам розклад
--
--  Виконуйте лише після того, як БЛОК 3 дав 200.
--
--  Кожні півгодини, на 13-й і 43-й хвилині. Не на нульовій і не на
--  тридцятій навмисно: там уже стоїть усе, що ставили «раз на пів
--  години», і ставати в ту саму чергу нема потреби. Заразом
--  розходимось із щогодинним fb-sync, який ходить на сьомій.
--
--  Хочете рідше — поміняйте розклад на '13 * * * *' (щогодини).
-- ════════════════════════════════════════════════════════════

select cron.schedule(
  'fb-comments-scan',
  '13,43 * * * *',
  $$
  select net.http_post(
    url := (select decrypted_secret from vault.decrypted_secrets
             where name = 'fb_comments_url'),
    headers := jsonb_build_object(
      'content-type', 'application/json',
      'x-cron-key',   (select decrypted_secret from vault.decrypted_secrets
                        where name = 'check_domains_cron_key')),
    body := '{"action":"scan"}'::jsonb,
    timeout_milliseconds := 120000
  );
  $$);


